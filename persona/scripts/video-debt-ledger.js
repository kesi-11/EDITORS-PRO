#!/usr/bin/env node
/**
 * video-debt-ledger.js
 *
 * Harvests every `video:` marker from the codebase and produces a
 * human-readable debt ledger. Inspired by ponytail's /ponytail-debt
 * command — a marker without a ceiling is debt rotting in silence;
 * this script surfaces all of them so they can be paid down.
 *
 * Run:  node persona/scripts/video-debt-ledger.js [--write]
 * Exit: 0 always (debt is not a CI failure; it's a tracking artifact).
 *
 * Output: stdout (and persona/DEBT.md if --write).
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..'); // project root
const OUT_PATH = path.resolve(__dirname, '..', 'DEBT.md');

// File extensions to scan for video: markers
const EXTENSIONS = new Set([
  '.rs', '.dart', '.js', '.ts', '.jsx', '.tsx', '.py',
  '.yaml', '.yml', '.toml', '.sh', '.md',
]);

// Skip directories
const SKIP_DIRS = new Set([
  '.git', 'node_modules', 'build', '.dart_tool', 'target',
  '.gradle', '.idea', '.vscode',
]);

function walk(dir, results = []) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch (e) {
    return results;
  }
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      walk(full, results);
    } else if (entry.isFile()) {
      const ext = path.extname(entry.name);
      if (EXTENSIONS.has(ext)) {
        results.push(full);
      }
    }
  }
  return results;
}

function scanFile(filePath) {
  const content = fs.readFileSync(filePath, 'utf8');
  const lines = content.split('\n');
  const findings = [];
  const pattern = /\bvideo:\s*(.+)$/i;
  lines.forEach((line, idx) => {
    // Strip leading comment markers
    const cleaned = line.replace(/^\s*(\/\/|#|;|\*)\s*/, '');
    const match = cleaned.match(pattern);
    if (match) {
      findings.push({
        line: idx + 1,
        text: match[1].trim(),
      });
    }
  });
  return findings;
}

function main() {
  const writeFlag = process.argv.includes('--write');

  console.log('Scanning for video: debt markers...\n');

  const files = walk(ROOT);
  const byFile = new Map();
  let total = 0;

  for (const file of files) {
    const findings = scanFile(file);
    if (findings.length > 0) {
      const rel = path.relative(ROOT, file);
      byFile.set(rel, findings);
      total += findings.length;
    }
  }

  const timestamp = new Date().toISOString();

  let out = '';
  out += `# EDITORS-PRO video: Debt Ledger\n\n`;
  out += `Generated: ${timestamp}\n`;
  out += `Total markers: ${total}\n`;
  out += `Files affected: ${byFile.size}\n\n`;
  out += `> Generated by \`persona/scripts/video-debt-ledger.js\`.\n`;
  out += `> A marker without its ceiling is debt rotting in silence.\n`;
  out += `> See \`persona/docs/video-debt-convention.md\` for syntax.\n\n`;

  if (total === 0) {
    out += `No \`video:\` markers found. Either the codebase has no deferred\n`;
    out += `shortcuts, or no one has marked them yet.\n`;
  } else {
    // Sort files alphabetically for stable output
    const sortedFiles = Array.from(byFile.keys()).sort();
    for (const file of sortedFiles) {
      const findings = byFile.get(file);
      out += `## ${file}\n`;
      for (const f of findings) {
        out += `- L${f.line}: ${f.text}\n`;
      }
      out += '\n';
    }

    // Summary by category (heuristic)
    const categories = new Map();
    for (const [, findings] of byFile) {
      for (const f of findings) {
        const lower = f.text.toLowerCase();
        let cat = 'other';
        if (/(lut|grade|color|chroma)/.test(lower)) cat = 'color';
        else if (/(loudness|lufs|audio|dialogue|track|mix)/.test(lower)) cat = 'audio';
        else if (/(stabil|motion|track|mask)/.test(lower)) cat = 'effects';
        else if (/(export|encode|codec|delivery|prores|h\.\d)/.test(lower)) cat = 'export';
        else if (/(proxy|cache|preview)/.test(lower)) cat = 'performance';
        else if (/(stub|placeholder|simulate|fake)/.test(lower)) cat = 'stub';
        categories.set(cat, (categories.get(cat) || 0) + 1);
      }
    }
    out += `## Summary by category\n\n`;
    out += `| Category | Markers |\n|---|---|\n`;
    const sortedCats = Array.from(categories.entries()).sort((a, b) => b[1] - a[1]);
    for (const [cat, count] of sortedCats) {
      out += `| ${cat} | ${count} |\n`;
    }
  }

  if (writeFlag) {
    fs.writeFileSync(OUT_PATH, out);
    console.log(`✅ Ledger written to ${path.relative(ROOT, OUT_PATH)} (${total} markers in ${byFile.size} files)`);
  } else {
    console.log(out);
    console.log(`\n(${total} markers in ${byFile.size} files — pass --write to save to persona/DEBT.md)`);
  }

  process.exit(0);
}

main();
